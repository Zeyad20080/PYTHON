print("Hello \bZoz")  # Backspace character
print("Hello \tZoz")  # Tab character
print("Hello \nZoz")  # Newline character
print("Hello \rZoz")  # Carriage return character
print("Hello \vZoz")  # Vertical tab character
print("Hello \\\\Zoz")  # Backslash character
print("Hello 'Zoz")  # Single quote character
print('Hello "Zoz')  # Double quote character
print("Hello \x48Zoz")  # Hexadecimal character
print("Hello \u0041Zoz")  # Unicode character